-- Apply once to the existing PostgreSQL schema before enabling GET /notifications.
BEGIN;

CREATE TABLE notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    type TEXT NOT NULL,
    title TEXT NOT NULL,
    message TEXT NOT NULL,
    resource_type TEXT,
    resource_id BIGINT,
    is_read BOOLEAN NOT NULL DEFAULT false,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX ix_notifications_user_created_at_id
    ON notifications (user_id, created_at DESC, id DESC);
CREATE INDEX ix_notifications_user_is_read_created_at_id
    ON notifications (user_id, is_read, created_at DESC, id DESC);

COMMIT;
